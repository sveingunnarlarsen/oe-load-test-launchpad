const query = (typeof req !== 'undefined' && req && req.query) || {};
const page = Math.max(Number(query.page || 1), 1);
const size = Math.min(Number(query.size || 50), 500);
const q = String(query.q || '').toLowerCase();
const started = Date.now();
const qb = entities.lt_order.createQueryBuilder('o');
if (q) qb.where('LOWER(o.customer) LIKE :q OR LOWER(o.product) LIKE :q OR LOWER(o.orderNo) LIKE :q', { q: '%' + q + '%' });
if (query.status) qb.andWhere('o.status = :status', { status: query.status });
const sortField = ['createdAt', 'amount', 'customer', 'status'].includes(query.sort) ? query.sort : 'createdAt';
qb.orderBy('o.' + sortField, query.dir === 'asc' ? 'ASC' : 'DESC').skip((page - 1) * size).take(size);
const [rows, total] = await qb.getManyAndCount();
const orderNos = rows.map((r) => r.orderNo);
const lines = orderNos.length ? await entities.lt_order_line.createQueryBuilder('l').where('l.orderNo IN (:...orderNos)', { orderNos }).getMany() : [];
const byOrder = {};
for (const line of lines) (byOrder[line.orderNo] = byOrder[line.orderNo] || []).push(line);
result.data = rows.map((r) => Object.assign({}, r, { lines: byOrder[r.orderNo] || [] }));
result.total = total;
result.page = page;
result.size = size;
result.ms = Date.now() - started;
